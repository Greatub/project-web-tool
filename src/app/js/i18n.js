// Single translation entry point for labels and messages. Placeholders {0}, {1}… take the extra arguments.
function t(key, ...args) {
  const value = I18N[curLang][key] ?? I18N.en[key] ?? key;
  if (typeof value !== "string") return value;
  return args.length ? value.replace(/\{(\d+)\}/g, (match, index) => String(args[index] ?? "")) : value;
}

function toggleLanguage() {
  curLang = curLang === "zh" ? "en" : "zh";
  try {
    localStorage.setItem("project-web-tool:language", curLang);
  } catch (e) {}
  applyStaticI18n();
  renderAll();
}

function inputError(key, ...args) {
  return new Error(t(key, ...args));
}
